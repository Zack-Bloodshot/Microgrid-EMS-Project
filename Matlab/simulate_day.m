function results = simulate_day(P_pv, P_load, params, tariff, alpha)
%SIMULATE_DAY Run all 4 EMS controllers on a given PV/load profile.
%   results = simulate_day(P_pv, P_load, params) runs Stage 0 (baseline),
%   Stage 1 (rule-based), Stage 2 (LP-based), and Stage 3 (degradation-aware
%   LP) controllers on the given profiles and returns a struct with stage0,
%   stage1, stage2, and stage3 results.
%
%   results = simulate_day(P_pv, P_load, params, tariff) additionally
%   uses a caller-supplied tariff struct (see tariff_params overrides).
%   Intended for sensitivity analysis.
%
%   results = simulate_day(P_pv, P_load, params, tariff, alpha) sets the
%   Stage 3 degradation weight alpha (dimensionless, default 1).
%
%   This is the single source of truth for the simulation pipeline.
%   Callers are responsible for attaching profile data (P_pv, P_load, time)
%   and any presentation-level adjustments.
%
%   See also: run_all_stages, prepare_cloudy_comparison, tariff_params.

    if nargin < 4 || isempty(tariff)
        tariff = tariff_params();
    end
    if nargin < 5 || isempty(alpha)
        alpha = 1;
    end

    % Stage 3 functions live in a subfolder; make the pipeline callable
    % without requiring every caller to manage the path.
    matlab_dir = fileparts(mfilename('fullpath'));
    addpath(fullfile(matlab_dir, 'Stage3'));

    % One wear model for every stage, so every reported degradation cost is
    % directly comparable.
    deg_model = sprintf('DoD %.0f%%, %d cycles', ...
        100*params.DoD_rated, params.N_cycles_rated);

    %% Stage 0: no-storage baseline
    % Degradation cost is genuinely zero: no battery is present.
    [P_gimp, P_gexp, P_curt] = rule_based_ems_p0(P_pv, P_load, params);
    validation = validate_power_balance_p0( ...
        P_pv, P_load, P_gimp, P_gexp, P_curt, params);
    [total_cost, cost] = calculate_costs(P_gimp, P_gexp, params.dt, tariff);

    results.stage0 = struct( ...
        'P_gimp', P_gimp, 'P_gexp', P_gexp, 'P_curt', P_curt, ...
        'validation', validation, 'cost', cost, ...
        'grid_cost', total_cost, 'degradation_cost', 0, ...
        'total_cost', total_cost);

    %% Stage 1: rule-based battery EMS
    [P_ch, P_dis, P_gimp, P_gexp, SOC, P_curt] = ...
        rule_based_ems_p1(P_pv, P_load, params);
    validation = validate_power_balance_p1( ...
        P_pv, P_load, P_ch, P_dis, P_gimp, P_gexp, SOC, P_curt, params);
    [total_cost, cost] = calculate_costs(P_gimp, P_gexp, params.dt, tariff);
    [deg_cost, EFC, DoD, LifeCycles] = battery_degradation(P_ch, P_dis, params);

    results.stage1 = struct( ...
        'P_ch', P_ch, 'P_dis', P_dis, 'P_gimp', P_gimp, ...
        'P_gexp', P_gexp, 'P_curt', P_curt, 'SOC', SOC, ...
        'validation', validation, 'cost', cost, ...
        'grid_cost', total_cost, 'degradation_cost', deg_cost, ...
        'total_cost', total_cost + deg_cost, 'EFC', EFC, ...
        'DoD', DoD, 'LifeCycles', LifeCycles, ...
        'degradation_model', deg_model);

    %% Stage 2: LP-based EMS with post-hoc degradation analysis
    [P_ch, P_dis, P_gimp, P_gexp, SOC, P_curt, grid_cost, deg_cost] = ...
        lp_naive_ems(P_pv, P_load, tariff, params);
    validation = validate_lp_solution( ...
        P_pv, P_load, P_ch, P_dis, P_gimp, P_gexp, SOC, P_curt, params);
    [deg_cost_check, EFC, DoD, LifeCycles] = ...
        battery_degradation(P_ch, P_dis, params);
    assert(abs(deg_cost_check - deg_cost) < 1e-9, ...
        'simulate_day:degCostMismatch', ...
        'Stage 2 degradation cost calculations disagree.');
    [grid_cost_check, cost] = calculate_costs(P_gimp, P_gexp, params.dt, tariff);
    assert(abs(grid_cost_check - grid_cost) < 1e-9, ...
        'simulate_day:gridCostMismatch', ...
        'Stage 2 grid cost calculations disagree.');

    results.stage2 = struct( ...
        'P_ch', P_ch, 'P_dis', P_dis, 'P_gimp', P_gimp, ...
        'P_gexp', P_gexp, 'P_curt', P_curt, 'SOC', SOC, ...
        'validation', validation, 'cost', cost, ...
        'grid_cost', grid_cost, 'degradation_cost', deg_cost, ...
        'total_cost', grid_cost + deg_cost, 'EFC', EFC, ...
        'DoD', DoD, 'LifeCycles', LifeCycles, ...
        'degradation_model', deg_model);

    %% Stage 3: degradation-aware LP with the shared wear model
    [P_ch, P_dis, P_gimp, P_gexp, SOC, P_curt, grid_cost, deg_cost, ...
        objective_value] = ...
        lp_degradation_aware_ems(P_pv, P_load, tariff, params, alpha);
    validation = validate_stage3_solution( ...
        P_pv, P_load, P_ch, P_dis, P_gimp, P_gexp, SOC, P_curt, params);
    [deg_cost_check, EFC, DoD, LifeCycles] = ...
        battery_degradation(P_ch, P_dis, params);
    assert(abs(deg_cost_check - deg_cost) < 1e-9, ...
        'simulate_day:stage3DegCostMismatch', ...
        'Stage 3 degradation cost calculations disagree.');
    [grid_cost_check, cost] = calculate_costs(P_gimp, P_gexp, params.dt, tariff);
    assert(abs(grid_cost_check - grid_cost) < 1e-9, ...
        'simulate_day:stage3GridCostMismatch', ...
        'Stage 3 grid cost calculations disagree.');

    results.stage3 = struct( ...
        'P_ch', P_ch, 'P_dis', P_dis, 'P_gimp', P_gimp, ...
        'P_gexp', P_gexp, 'P_curt', P_curt, 'SOC', SOC, ...
        'validation', validation, 'cost', cost, ...
        'grid_cost', grid_cost, 'degradation_cost', deg_cost, ...
        'total_cost', grid_cost + deg_cost, 'EFC', EFC, ...
        'DoD', DoD, 'LifeCycles', LifeCycles, ...
        'alpha', alpha, 'objective_value', objective_value, ...
        'degradation_model', deg_model);
end
